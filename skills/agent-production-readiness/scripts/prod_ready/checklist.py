"""Production-Readiness Checklist v3 — per-target catalog loaded from ``catalog_v3.json``.

The single source of truth is ``catalog_v3.json`` (generated alongside ``docs/checklist-v3-spec.md`` and
``web/static/checklist.html``). This module only *loads* it and adds engine metadata
(verification commands, target files, tunable custom fields, legacy ``C*`` aliases).

Categories (5): State & Memory (F) · Runtime Lifecycle (O) · CI/CD & Evaluation (D) · Observability (OB) · Security & Governance (S)

Per-target item counts:
- Agent Runtime (``agent_runtime``): 10 (AR-F1 … AR-S5; AR-S4 Code Execution · conditional code)
- Cloud Run (``cloud_run``)       : 11 (CR-F1 … CR-S6; CR-S5 Cloud Run sandboxes · Preview · conditional code)
- GKE (``gke``)                    : 12 (GKE-F1 … GKE-S5; GKE-O2 idle suspend/resume on Agent Substrate)

``AR-S5`` / ``CR-S6`` / ``GKE-S5`` — user-delegated auth (Agent Identity auth manager) · Preview · conditional
``delegated`` (external tools / MCP servers called on behalf of users). Guidance only (never auto-patched).

CI/CD & Evaluation has two items per target: ``*-D1`` CI/CD pipeline generated by agents-cli (guidance only —
the engine never generates pipeline files) and ``*-D2`` eval dataset + score-threshold gate in that pipeline.

Cloud Run / Agent Runtime currently have no Runtime Lifecycle (O) item; reports skip empty categories.
Gemini call retry · endpoint (``retry_options`` / ``GOOGLE_CLOUD_LOCATION``) is ADK agent-code territory:
it is out of scope (ADK optimization) — never checked, patched, or listed as an advisory.

Grades:
- ``required``    — always scored.
- ``conditional`` — scored only when its workload condition (conv / memory / code / tools / idle / delegated) is met,
  else N/A.
  ``idle`` cannot be inferred from code: it is met only when Agent Substrate is already used or the user opts in
  (``--conditions idle=true`` / ``scan_project(conditions={"idle": True})``).
  ``delegated`` is auto-detected from tool credentials (MCP / OpenAPI / third-party API tools with auth headers,
  ``*_TOKEN`` / ``*_API_KEY`` / ``GITHUB_PAT`` env vars, auth manager usage); otherwise opt in with
  ``--conditions delegated=true``.
- ``preview``     — status is reported but never blocks the overall Production Ready verdict.

General platform best practices (health probes, PDB/HPA, Terraform IaC drift, alert policies,
Secret pinning, Non-Root, Direct VPC / PSC-I, NetworkPolicy, PSS) are **delegated** to the
platform skills in https://github.com/google/skills/tree/main/skills/cloud and are not scored.
"""

