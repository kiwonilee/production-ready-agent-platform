@dataclass(frozen=True)
class CustomFieldSpec:
    key: str
    label: str
    default: str
    options: list[str] = field(default_factory=list)


@dataclass
class CustomParams:
    workload_type: str = "service"
    agent_engine_id: str = ""
    vpc_network_name: str = "default"
    vpc_subnet_name: str = "default"
    subnet_cidr: str = "10.128.64.0/28"
    egress_mode: str = "PRIVATE_RANGES_ONLY"
    latency_p95_ms: int = 15000
    agent_gateway_enforcement_mode: str = "DRY_RUN"
    agent_gateway_direction: str = "egress"          # "egress" | "ingress" | "both"
    enable_model_armor: bool = False                 # Attach Model Armor content guardrails on Agent Gateway
    cloud_run_identity_mode: str = "agent_identity"  # "agent_identity" | "service_account"
    organization_id: str = ""                        # Optional GCP Organization ID for SPIFFE principal
    eval_threshold: float = 3.5
    # GKE-native cluster / execution pattern / graceful drain tuning
    gke_cluster_mode: str = "autopilot"
    gke_execution_pattern: str = "standard_pods"
    gke_enable_gvisor: bool = False
    gke_termination_grace_seconds: int = 120

    @classmethod
    def from_dict(cls, data: dict[str, Any] | None) -> CustomParams:
        if not data:
            return cls()
        instance = cls()
        for k, v in data.items():
            if k not in cls.__dataclass_fields__:
                continue
            current = getattr(instance, k)
            if isinstance(current, bool):
                if isinstance(v, bool):
                    setattr(instance, k, v)
                elif isinstance(v, str):
                    setattr(instance, k, v.strip().lower() in ("true", "1", "yes", "on"))
                else:
                    setattr(instance, k, bool(v))
            else:
                field_type = type(current)
                try:
                    setattr(instance, k, field_type(v))
                except Exception:
                    pass
        return instance

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


@dataclass(frozen=True)
class ChecklistItemSpec:
    """One v3 checklist item (each item belongs to exactly one runtime target)."""

    id: str
    target: TargetType
    category: str
    title: str
    check: str
    best_practice: str
    references: tuple[tuple[str, str], ...]
    grade: GradeType
    condition: str | None
    preview: bool
    new: bool
    verify_cmd: str
    target_files: tuple[str, ...]
    custom_fields: tuple[CustomFieldSpec, ...] = ()
    legacy_ids: tuple[str, ...] = ()
    auto_patch: bool = True

    # ---- v2-compatible accessors (used by scanner / reports / web) ----
    @property
    def code_alias(self) -> str:
        return self.id

    @property
    def domain_id(self) -> str:
        return self.category

    @property
    def category_name(self) -> str:
        return CATEGORY_BY_CODE.get(self.category, {}).get("name", self.category)

    @property
    def category_sub(self) -> str:
        return CATEGORY_BY_CODE.get(self.category, {}).get("sub", "")

    @property
    def domain_name(self) -> str:
        sub = self.category_sub
        return f"{self.category_name} ({sub})" if sub else self.category_name

    @property
    def severity(self) -> str:
        return GRADE_LABEL.get(self.grade, self.grade)

    @property
    def condition_label(self) -> str:
        return CONDITIONS.get(self.condition or "", "")

    @property
    def applicable_targets(self) -> tuple[TargetType, ...]:
        return (self.target,)

    @property
    def references_list(self) -> list[dict[str, str]]:
        return [{"label": label, "url": url} for label, url in self.references]

    def applies_to(self, target: TargetType) -> bool:
        return target == self.target

    def title_for(self, target: TargetType | None = None) -> str:
        return self.title

    def why_for(self, target: TargetType | None = None) -> str:
        return self.check

    def desc_for(self, target: TargetType | None = None) -> str:
        return self.best_practice

    def verify_cmd_for(self, target: TargetType | None = None) -> str:
        return self.verify_cmd

    def target_files_for(self, target: TargetType | None = None) -> list[str]:
        return list(self.target_files)

    def custom_fields_for(self, target: TargetType | None = None) -> list[CustomFieldSpec]:
        return list(self.custom_fields)


