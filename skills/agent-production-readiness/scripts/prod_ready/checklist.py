def _build_items() -> list[ChecklistItemSpec]:
    items: list[ChecklistItemSpec] = []
    for target in ALL_TARGETS:
        for raw in CATALOG.get("items", {}).get(target, []):
            meta = _ITEM_META.get(raw["id"], {})
            items.append(
                ChecklistItemSpec(
                    id=raw["id"],
                    target=target,
                    category=raw["category"],
                    title=raw["title"],
                    check=raw.get("check", ""),
                    best_practice=raw.get("best_practice", ""),
                    references=tuple((r.get("label", ""), r.get("url", "")) for r in raw.get("references", [])),
                    grade=raw.get("grade", "required"),
                    condition=raw.get("condition"),
                    preview=bool(raw.get("preview", False)),
                    new=bool(raw.get("new", False)),
                    verify_cmd=meta.get("verify", ""),
                    target_files=tuple(meta.get("files", ())),
                    custom_fields=tuple(meta.get("fields", ())),
                    legacy_ids=tuple(meta.get("legacy", ())),
                    auto_patch=bool(meta.get("auto_patch", True)),
                )
            )
    return items


