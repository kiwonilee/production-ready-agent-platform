def _canonical_legacy(token: str) -> str:
    return _PRE_V25_ALIASES.get(token, token)


@dataclass
class ItemSelection:
    """Result of resolving a user selection (``--items``) against the v3 catalog."""

    ids: list[str]
    explicit: bool
    delegated_legacy: list[str] = field(default_factory=list)
    out_of_scope_legacy: list[str] = field(default_factory=list)
    unknown: list[str] = field(default_factory=list)
    legacy_resolved: dict[str, list[str]] = field(default_factory=dict)


def resolve_item_selection(requested: list[str] | None, target: TargetType | None = None) -> ItemSelection:
    """Resolves 'ALL', v3 ids, and legacy ``C*`` aliases — scoped to ``target`` when supplied."""
    pool = get_items_for_target(target) if target is not None else CHECKLIST_ITEMS
    allowed = [item.id for item in pool]
    allowed_set = set(allowed)

    tokens = [t.strip().upper() for t in (requested or []) if t and t.strip()]
    if not tokens or "ALL" in tokens:
        return ItemSelection(ids=allowed, explicit=False)

    resolved: list[str] = []
    seen: set[str] = set()
    sel = ItemSelection(ids=resolved, explicit=True)

    def _add(item_id: str) -> None:
        if item_id in allowed_set and item_id not in seen:
            seen.add(item_id)
            resolved.append(item_id)

    for token in tokens:
        if token in ITEM_BY_ID:
            _add(token)
            continue
        legacy = _canonical_legacy(token)
        if legacy in OUT_OF_SCOPE_LEGACY_NOTES:
            sel.out_of_scope_legacy.append(token)
            continue
        if legacy in LEGACY_ID_MAP:
            targets = [target] if target is not None else list(ALL_TARGETS)
            mapped: list[str] = []
            for t in targets:
                mapped.extend(LEGACY_ID_MAP[legacy].get(t, []))
            if mapped:
                sel.legacy_resolved[token] = mapped
                for m in mapped:
                    _add(m)
            else:
                sel.delegated_legacy.append(token)
            continue
        sel.unknown.append(token)
    return sel


def resolve_item_ids(requested: list[str] | None, target: TargetType | None = None) -> list[str]:
    """Resolves a selection to v3 ids (legacy ``C*`` aliases supported; delegated / out-of-scope ids resolve to nothing)."""
    return resolve_item_selection(requested, target).ids


def platform_skill_url(name: str) -> str:
    return f"{PLATFORM_SKILLS_REPO}/{name}"


def platform_skills_for(target: TargetType) -> list[dict[str, str]]:
    """Platform skills (google/skills) recommended for the target's delegated general best practices."""
    return [
        {"name": n, "url": platform_skill_url(n)}
        for n in CATALOG.get("platform_skills", {}).get(target, [])
    ]


def delegated_bps() -> list[dict[str, str]]:
    return [dict(d) for d in CATALOG.get("delegated_platform_bps", [])]


def advisories_for(target: TargetType) -> list[dict[str, str]]:
    return [
        {"title": a.get("title", ""), "when": a.get("when", "")}
        for a in CATALOG.get("advisories", [])
        if target in a.get("targets", [])
    ]
